#!/usr/bin/env python3
"""Pack the existing battle UI losslessly into its shared VRAM tile range.

Run from the repository root after building tools/gbagfx/gbagfx.
Only exact tiles and their hardware-supported flips are deduplicated.
The generated header is committed, so normal builds need no Python packages.
"""
from pathlib import Path
import struct
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
GFX = ROOT / "graphics/battle_interface"
BASE = 0x110
LIMIT = 0x16E  # The next window owns tile 0x16e.


def flip(tile, flags):
    rows = [tile[i:i + 8] for i in range(0, 64, 8)]
    if flags & 0x400:
        rows = [row[::-1] for row in rows]
    if flags & 0x800:
        rows = rows[::-1]
    return bytes(x for row in rows for x in row)


def emit(name, data, bits):
    values = struct.unpack("<" + {16: "H", 32: "I"}[bits] * (len(data) // (bits // 8)), data)
    lines = [f"const u{bits} {name}[] = {{"]
    for i in range(0, len(values), 8):
        lines.append("    " + ", ".join(f"0x{x:0{bits // 4}X}" for x in values[i:i + 8]) + ",")
    return "\n".join(lines + ["};", ""])


atlas = []
maps = []
with tempfile.TemporaryDirectory() as temp:
    for kind in ("action", "message", "move"):
        raw_path = Path(temp) / "tiles.4bpp"
        subprocess.run([str(ROOT / "tools/gbagfx/gbagfx"), str(GFX / f"textbox_{kind}.png"), str(raw_path)], check=True)
        raw = raw_path.read_bytes()
        pixels = bytes(v for b in raw for v in (b & 15, b >> 4))
        tiles = [pixels[i:i + 64] for i in range(0, len(pixels), 64)]
        for suffix, symbol_suffix in (("map", "Tilemap"), ("cursor_map", "CursorTilemap")):
            path = GFX / f"textbox_{kind}_{suffix}.bin"
            if not path.exists():
                continue
            old = struct.unpack("<" + "H" * (path.stat().st_size // 2), path.read_bytes())
            remapped = []
            for entry in old:
                source = tiles[(entry & 0x3FF) - BASE]
                for index, tile in enumerate(atlas):
                    flags = next((f for f in (0, 0x400, 0x800, 0xC00) if flip(tile, f) == source), None)
                    if flags is not None:
                        break
                else:
                    index, flags = len(atlas), 0
                    atlas.append(source)
                new = (entry & 0xF000) | ((entry & 0xC00) ^ flags) | (BASE + index)
                assert flip(atlas[index], new & 0xC00) == flip(source, entry & 0xC00)
                remapped.append(new)
            maps.append(emit(f"gKyotoBattle{kind.title()}{symbol_suffix}", struct.pack("<" + "H" * len(remapped), *remapped), 16))

assert BASE + len(atlas) <= LIMIT, "Battle UI atlas overlaps a text window"
packed = bytes(t[i] | (t[i + 1] << 4) for t in atlas for i in range(0, 64, 2))
header = "// Generated by tools/pack_kyoto_battle_ui.py; edit the original UI assets.\n"
header += f"// {len(atlas)} tiles: 0x{BASE:X} through 0x{BASE + len(atlas) - 1:X}.\n"
header += emit("gKyotoBattleUiTiles", packed, 32) + "\n".join(maps)
output = ROOT / "src/data/kyoto_battle_ui.h"
if not output.exists() or output.read_text() != header:
    output.write_text(header)
# Keep the declared array bound used by sizeof in battle_bg.c in sync when
# an artist changes the original UI. Avoid touching files on a no-op run.
declarations = ROOT / "include/graphics.h"
old_declarations = declarations.read_text()
new_declarations, count = re.subn(r"extern const u32 gKyotoBattleUiTiles\[[^]]*\];",
    f"extern const u32 gKyotoBattleUiTiles[{len(atlas)} * 8];", old_declarations)
assert count == 1, "Missing shared battle UI declaration"
if new_declarations != old_declarations:
    declarations.write_text(new_declarations)
print(f"Packed and pixel-verified {len(atlas)} tiles and {len(maps)} tilemaps.")
